package ru.ylab.levon.service.api;

/**
 * Универсальный интерфейс сервиса кеширования.
 * <p>
 * Определяет базовые операции для хранения, получения и управления
 * элементами кеша.
 *
 * @param <K> тип ключей
 * @param <V> тип значений
 */
public interface CacheService<K, V> {
    /**
     * Возвращает значение, связанное с указанным ключом.
     *
     * @param key ключ элемента
     * @return значение или {@code null}, если элемент отсутствует
     */
    V get(K key);

    /**
     * Добавляет элемент в кеш или обновляет существующий.
     *
     * @param key   ключ элемента
     * @param value сохраняемое значение
     */
    void put(K key, V value);

    /**
     * Проверяет наличие элемента по указанному ключу.
     *
     * @param key ключ элемента
     * @return {@code true}, если элемент присутствует, иначе {@code false}
     */
    boolean contains(K key);

    /**
     * Полностью очищает кеш, удаляя все элементы.
     */
    void clear();

    /**
     * Возвращает текущее количество элементов в кеше.
     *
     * @return число сохранённых элементов
     */
    int size();
}
